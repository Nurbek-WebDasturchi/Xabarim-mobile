const Lang = {
  get: () => localStorage.getItem("lang") || "uz",
  set(l) {
    localStorage.setItem("lang", l);
    document.documentElement.lang = l;
    Lang.apply();
  },
  t(k, p = {}) {
    let s = (I18N[Lang.get()] || {})[k] ?? I18N.uz[k] ?? k;
    for (const x in p) s = s.replace("{" + x + "}", p[x]);
    return s;
  },
  apply() {
    document
      .querySelectorAll("[data-i18n]")
      .forEach((e) => (e.textContent = Lang.t(e.dataset.i18n)));
    document
      .querySelectorAll("[data-i18n-ph]")
      .forEach((e) => (e.placeholder = Lang.t(e.dataset.i18nPh)));
    document
      .querySelectorAll(".lang-switch")
      .forEach((s) => (s.value = Lang.get()));
  },
  init(cb) {
    const slot = document.getElementById("lang-slot");
    if (slot) {
      slot.innerHTML =
        '<select class="form-select form-select-sm lang-switch" aria-label="Language"><option value="uz">O\u2018zbekcha</option><option value="en">English</option><option value="ru">Русский</option></select>';
      slot.firstChild.onchange = (e) => {
        Lang.set(e.target.value);
        cb && cb();
      };
    }
    document.documentElement.lang = Lang.get();
    Lang.apply();
  },
};
